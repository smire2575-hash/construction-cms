-- Receive stock with moving weighted average. Backend checks subscription, tenant and role before calling.
create or replace function public.cms_receive_stock(
 p_company uuid,p_actor uuid,p_product uuid,p_qty numeric,p_unit_cost numeric,p_reference text default ''
) returns uuid language plpgsql security definer set search_path=public as $$
declare v_product record;v_warehouse uuid;v_branch uuid;v_qty numeric(18,3);
 v_new_cost numeric(16,4);v_journal uuid;v_movement uuid;v_total numeric(16,2);
begin
 if p_qty<=0 or p_unit_cost<0 then raise exception 'Quantity must be positive; cost cannot be negative';end if;
 select * into v_product from public.products where company_id=p_company and id=p_product for update;
 if not found then raise exception 'Product not found in company';end if;
 select w.id,w.branch_id into v_warehouse,v_branch from public.warehouses w
 where w.company_id=p_company and w.status='Active' order by w.id limit 1;
 if v_warehouse is null then raise exception 'No active warehouse';end if;
 select coalesce(sum(quantity_on_hand),0) into v_qty from public.stock_balances
 where company_id=p_company and product_id=p_product;
 v_new_cost:=round((v_qty*v_product.cost+p_qty*p_unit_cost)/(v_qty+p_qty),4);
 update public.products set cost=v_new_cost where id=p_product and company_id=p_company;
 insert into public.stock_balances(company_id,warehouse_id,product_id,quantity_on_hand)
 values(p_company,v_warehouse,p_product,p_qty)
 on conflict(warehouse_id,product_id) do update set quantity_on_hand=public.stock_balances.quantity_on_hand+excluded.quantity_on_hand;
 insert into public.stock_movements(company_id,warehouse_id,product_id,quantity_delta,unit_cost,source_type)
 values(p_company,v_warehouse,p_product,p_qty,p_unit_cost,'RECEIPT') returning id into v_movement;
 v_total:=round(p_qty*p_unit_cost,2);
 if v_total>0 then
  insert into public.journal_entries(company_id,branch_id,source_type,source_id,memo)
  values(p_company,v_branch,'STOCK_RECEIPT',v_movement,coalesce(nullif(p_reference,''),'Stock receipt')) returning id into v_journal;
  insert into public.journal_lines(company_id,journal_id,account_code,debit,credit) values
  (p_company,v_journal,'1200',v_total,0),
  (p_company,v_journal,'2100',0,v_total); -- Goods received / not invoiced clearing liability
 end if;
 insert into public.audit_events(company_id,actor,action,entity_type,entity_id,metadata)
 values(p_company,p_actor,'receive_stock','stock_movement',v_movement,jsonb_build_object('quantity',p_qty,'reference',p_reference));
 return v_movement;
end $$;

create or replace function public.cms_record_sale_payment(
 p_company uuid,p_actor uuid,p_sale uuid,p_amount numeric,p_method text
) returns uuid language plpgsql security definer set search_path=public as $$
declare v_sale record;v_paid numeric(16,2);v_payment uuid;v_journal uuid;
begin
 if p_amount<=0 then raise exception 'Payment must be positive';end if;
 if p_method not in ('Cash','Bank','Mobile Money','Other') then raise exception 'Invalid method';end if;
 select * into v_sale from public.sales where company_id=p_company and id=p_sale for update;
 if not found then raise exception 'Sale not found';end if;
 if v_sale.status='Pending' then raise exception 'Cannot receive invoice payment against an undelivered order';end if;
 select coalesce(sum(amount),0) into v_paid from public.payments where company_id=p_company and sale_id=p_sale;
 if v_paid+p_amount>v_sale.total then raise exception 'Payment exceeds outstanding invoice';end if;
 insert into public.payments(company_id,sale_id,amount,method) values(p_company,p_sale,p_amount,p_method) returning id into v_payment;
 insert into public.journal_entries(company_id,branch_id,source_type,source_id,memo)
 values(p_company,v_sale.branch_id,'CUSTOMER_RECEIPT',v_payment,'Receipt against '||v_sale.reference) returning id into v_journal;
 insert into public.journal_lines(company_id,journal_id,account_code,debit,credit) values
  (p_company,v_journal,'1000',p_amount,0),
  (p_company,v_journal,'1100',0,p_amount);
 update public.sales set status=case when v_paid+p_amount>=v_sale.total then 'Paid' else 'Partial' end
 where company_id=p_company and id=p_sale;
 insert into public.audit_events(company_id,actor,action,entity_type,entity_id,metadata)
 values(p_company,p_actor,'record_payment','payment',v_payment,jsonb_build_object('sale_id',p_sale,'amount',p_amount));
 return v_payment;
end $$;

